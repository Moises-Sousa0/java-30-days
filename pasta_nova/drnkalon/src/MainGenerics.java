import java.util.*;

public class MainGenerics {
    public static void main(String[] args) {
        String[] pecas = new String[3];
         pecas[0] = "Oleo";
         pecas[1] = "Pastilha";
         pecas[2] = "Filtro";

        System.out.println(pecas[0]);
        System.out.println(pecas[1]);
        System.out.println(pecas[2]);

    }
}
